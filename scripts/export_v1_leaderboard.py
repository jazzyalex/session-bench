#!/usr/bin/env python3
"""Write data/leaderboard-v1.yml from the v1 release, for a hosted view.

The file is generated from `artifacts/survival-v1-release/` (scorecard,
leaderboard and the notes of the report). It holds no measurement of its own.
A site that shows the v1 table copies this file byte for byte.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RELEASE = ROOT / 'artifacts/survival-v1-release'
NOTES = ROOT / 'plans/survival-v1/release-notes-v1.json'
HEADER = ('# GENERATED by scripts/export_v1_leaderboard.py — do not hand-edit.\n'
          '# Inputs: artifacts/survival-v1-release/ + plans/survival-v1/release-notes-v1.json.\n')
CATEGORIES = (('record_fidelity', 'Record fidelity', 30), ('causality_context', 'Causality and context', 20),
              ('usage_attribution', 'Usage and attribution', 15), ('portability_openness', 'Portability and openness', 20),
              ('durability_signal', 'Durability and signal', 15))
BASE = 'https://github.com/jazzyalex/session-bench/blob/main/'


def build(release=RELEASE, notes=NOTES):
    card = json.loads((release / 'scorecard.json').read_bytes())
    rows = list(csv.DictReader((release / 'leaderboard.csv').open()))
    scores = {row['configuration_id']: row for row in card['scores']}
    first = {}
    for run in card['runs']:
        first.setdefault(run['configuration_id'], run['identity'])
    ranked, other = [], []
    for row in rows:
        config = row['configuration_id']
        if row['rank']:
            score, identity = scores[config], first[config]
            ranked.append({'rank': int(row['rank']), 'id': config, 'name': row['surface'], 'score': row['overall'],
                           'runs': int(row['sample_size']), 'build': identity['build'], 'model': identity['model'],
                           'categories': {key: score['categories'][key] for key, _, _ in CATEGORIES},
                           'adapter_url': None})
        else:
            other.append({'id': config, 'name': row['surface'],
                          'status': 'shares the Codex CLI row' if row['evidence_kind'] == 'shared_format' else 'not scored yet'})
    documents = {'claude-cli': 'claude-code', 'claude-desktop': 'claude-code', 'opencode-cli': 'opencode-cli',
                 'deepseek-harness-cli': 'deepseek-harness', 'cursor-cli': 'cursor', 'codex-cli': 'codex-cli'}
    for row in ranked:
        name = documents.get(row['id'], row['id'])
        # Pi has no adapter document; its review record in the release is the reference.
        row['adapter_url'] = (BASE + f'docs/survival-v1/adapters/{name}.md' if (ROOT / f'docs/survival-v1/adapters/{name}.md').is_file()
                              else BASE + f'artifacts/survival-v1-release/evidence/{row["id"]}/independent-review.json')
    note = json.loads(notes.read_bytes())
    return {'version': '1.0', 'release_date': '2026-10-08', 'generated_by': 'scripts/export_v1_leaderboard.py',
            'source_repository': 'https://github.com/jazzyalex/session-bench',
            'release_manifest_sha256': hashlib.sha256((release / 'release-manifest.json').read_bytes()).hexdigest(),
            'report_url': BASE + 'artifacts/survival-v1-release/REPORT.md',
            'reproduce_url': BASE + 'artifacts/survival-v1-release/REPRODUCE.md',
            'rubric_url': BASE + 'docs/survival-v1/rubric.md',
            'metrics': 31, 'runs_per_row': 3,
            'categories': [{'id': key, 'name': name, 'points': points} for key, name, points in CATEGORIES],
            'agents': sorted(ranked, key=lambda row: row['rank']), 'not_ranked': other,
            'waived_and_corrected_rules': [row['text'] for row in note['footnotes']], 'known_limits': note['limits']}


def render(document):
    return HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=1000)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT / 'data/leaderboard-v1.yml')
    parser.add_argument('--check', action='store_true', help='fail if the file differs from the generated text')
    args = parser.parse_args()
    text = render(build())
    if args.check:
        raise SystemExit(0 if args.out.read_text() == text else f'{args.out} is stale')
    args.out.write_text(text)
